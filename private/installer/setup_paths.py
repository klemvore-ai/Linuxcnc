#!/usr/bin/env python3
"""LinuxCNC path configuration installer.

This script sets up the correct paths for the LinuxCNC installation
by generating the appropriate configuration files.
"""

import os
import sys
import shutil
from pathlib import Path


def read_paths_config(config_path="/etc/linuxcnc/paths.conf"):
    """Read the paths configuration file."""
    paths = {}
    if not os.path.exists(config_path):
        print(f"Warning: {config_path} not found, using defaults")
        return paths

    with open(config_path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if "=" in line:
                key, value = line.split("=", 1)
                paths[key.strip()] = value.strip()
    return paths


def generate_agent_env(paths, output_path="/etc/linuxcnc/agent.env"):
    """Generate the agent environment file."""
    lines = [
        "# LinuxCNC Agent Environment",
        "# Generated by setup_paths.py",
        "",
        f"LINUXCNC_AGENT_BIND={paths.get('LINUXCNC_AGENT_BIND', '0.0.0.0')}",
        f"LINUXCNC_AGENT_PORT={paths.get('LINUXCNC_AGENT_PORT', '9443')}",
        f"LINUXCNC_CLIENT_FINGERPRINT={paths.get('LINUXCNC_CLIENT_FINGERPRINT', '')}",
        "",
        "# Paths",
        f"LINUXCNC_CONFIG_ROOT={paths.get('LINUXCNC_CONFIG_ROOT', '/home/operator/linuxcnc/configs')}",
        f"LINUXCNC_GCODE_ROOT={paths.get('LINUXCNC_GCODE_ROOT', '/home/operator/linuxcnc/nc_files')}",
        f"LINUXCNC_AGENT_ROOT={paths.get('LINUXCNC_AGENT_ROOT', '/opt/LinuxCNC')}",
    ]

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Generated: {output_path}")


def generate_systemd_override(paths, output_path="/etc/systemd/system/linuxcnc-agent.service.d/override.conf"):
    """Generate systemd override for custom paths."""
    config_root = paths.get("LINUXCNC_CONFIG_ROOT", "/home/operator/linuxcnc/configs")
    gcode_root = paths.get("LINUXCNC_GCODE_ROOT", "/home/operator/linuxcnc/nc_files")

    lines = [
        "[Service]",
        f"ReadWritePaths=/var/lib/linuxcnc/updates /var/lib/linuxcnc/updates/tmp {config_root} {gcode_root}",
    ]

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Generated: {output_path}")


def update_linuxcnc_ini(paths, ini_path):
    """Update LinuxCNC INI with correct SUBROUTINE_PATH."""
    gcode_root = paths.get("LINUXCNC_GCODE_ROOT", "/home/operator/linuxcnc/nc_files")

    if not os.path.exists(ini_path):
        print(f"Warning: {ini_path} not found, skipping INI update")
        return

    with open(ini_path) as f:
        content = f.read()

    # Update SUBROUTINE_PATH
    if "SUBROUTINE_PATH" in content:
        lines = content.split("\n")
        for i, line in enumerate(lines):
            if line.strip().startswith("SUBROUTINE_PATH"):
                lines[i] = f"SUBROUTINE_PATH = {gcode_root}"
                break
        content = "\n".join(lines)

        # Backup original
        shutil.copy2(ini_path, ini_path + ".bak")
        with open(ini_path, "w") as f:
            f.write(content)
        print(f"Updated: {ini_path} (backup: {ini_path}.bak)")


def main():
    print("LinuxCNC Path Configuration")
    print("=" * 40)

    # Read configuration
    config_path = sys.argv[1] if len(sys.argv) > 1 else "/etc/linuxcnc/paths.conf"
    print(f"Reading: {config_path}")
    paths = read_paths_config(config_path)

    # Generate files
    generate_agent_env(paths)
    generate_systemd_override(paths)

    # Update LinuxCNC INI if specified
    ini_path = paths.get("LINUXCNC_INI_PATH")
    if ini_path:
        update_linuxcnc_ini(paths, ini_path)

    print()
    print("Done. Reload systemd and restart services:")
    print("  sudo systemctl daemon-reload")
    print("  sudo systemctl restart linuxcnc-hal-helper")
    print("  sudo systemctl restart linuxcnc-agent")


if __name__ == "__main__":
    main()
